package com.example.notary.db;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Паттерн «Одиночка» (Singleton) — единственное подключение к встраиваемой СУБД H2.
 * Используется всеми репозиториями; схема создаётся при первом обращении.
 * Потокобезопасная инициализация — двойная проверка с блокировкой.
 */
public final class Database {

    private static final String URL = "jdbc:h2:./data/notarydb";
    private static final String USER = "sa";
    private static final String PASSWORD = "";

    private static volatile Database instance;

    private final Connection connection;

    private Database() {
        try {
            Files.createDirectories(Path.of("data"));
            this.connection = DriverManager.getConnection(URL, USER, PASSWORD);
            initSchema();
        } catch (Exception e) {
            throw new IllegalStateException("Не удалось инициализировать базу данных H2", e);
        }
    }

    /** Единственная точка доступа к экземпляру. */
    public static Database getInstance() {
        if (instance == null) {
            synchronized (Database.class) {
                if (instance == null) {
                    instance = new Database();
                }
            }
        }
        return instance;
    }

    public Connection getConnection() {
        return connection;
    }

    /** Схема соответствует модели данных из архитектурного плана. */
    private void initSchema() throws SQLException {
        String[] ddl = {
                "CREATE TABLE IF NOT EXISTS clients ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "full_name VARCHAR(255) NOT NULL,"
                        + "passport_data VARCHAR(50) NOT NULL,"
                        + "phone VARCHAR(30),"
                        + "email VARCHAR(255),"
                        + "auth_data VARCHAR(255))",
                "CREATE TABLE IF NOT EXISTS services ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "name VARCHAR(255) NOT NULL,"
                        + "description VARCHAR(1000),"
                        + "price DECIMAL(15,2) NOT NULL,"
                        + "pricing_type VARCHAR(20) NOT NULL)",
                "CREATE TABLE IF NOT EXISTS applications ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "client_id BIGINT NOT NULL REFERENCES clients(id),"
                        + "service_id BIGINT NOT NULL REFERENCES services(id),"
                        + "status VARCHAR(20) NOT NULL,"
                        + "note VARCHAR(1000),"
                        + "created_at TIMESTAMP NOT NULL)",
                "CREATE TABLE IF NOT EXISTS documents ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "application_id BIGINT NOT NULL REFERENCES applications(id),"
                        + "file_url VARCHAR(500) NOT NULL,"
                        + "type VARCHAR(20) NOT NULL,"
                        + "signed BOOLEAN NOT NULL DEFAULT FALSE)",
                "CREATE TABLE IF NOT EXISTS payments ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "application_id BIGINT NOT NULL REFERENCES applications(id),"
                        + "amount DECIMAL(15,2) NOT NULL,"
                        + "status VARCHAR(20) NOT NULL,"
                        + "created_at TIMESTAMP NOT NULL)",
                "CREATE TABLE IF NOT EXISTS notifications ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "client_id BIGINT NOT NULL REFERENCES clients(id),"
                        + "application_id BIGINT REFERENCES applications(id),"
                        + "type VARCHAR(30) NOT NULL,"
                        + "message VARCHAR(2000) NOT NULL,"
                        + "status VARCHAR(20) NOT NULL,"
                        + "created_at TIMESTAMP NOT NULL)",
                "CREATE TABLE IF NOT EXISTS audit_log ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "event_type VARCHAR(50) NOT NULL,"
                        + "description VARCHAR(2000) NOT NULL,"
                        + "created_at TIMESTAMP NOT NULL)"
        };
        try (Statement statement = connection.createStatement()) {
            for (String sql : ddl) {
                statement.execute(sql);
            }
        }
    }
}
