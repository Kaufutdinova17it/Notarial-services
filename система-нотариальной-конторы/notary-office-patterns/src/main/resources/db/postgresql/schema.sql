BEGIN;

CREATE TABLE IF NOT EXISTS clients (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(255) NOT NULL,
    passport_data VARCHAR(50) NOT NULL,
    phone         VARCHAR(30),
    email         VARCHAR(255) NOT NULL UNIQUE,
    auth_data     VARCHAR(255) NOT NULL,
    CONSTRAINT clients_email_format CHECK (position('@' IN email) > 1)
);

CREATE TABLE IF NOT EXISTS services (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL UNIQUE,
    description  VARCHAR(1000),
    price        NUMERIC(15, 2) NOT NULL CHECK (price >= 0),
    pricing_type VARCHAR(20) NOT NULL,
    CONSTRAINT services_pricing_type_check
        CHECK (pricing_type IN ('FIXED', 'PERCENTAGE', 'PRIVILEGED'))
);

CREATE TABLE IF NOT EXISTS applications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
    service_id BIGINT NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
    status     VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    note       VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT applications_status_check
        CHECK (status IN ('CREATED', 'IN_PROGRESS', 'READY', 'RECEIVED', 'REJECTED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS documents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    file_url       VARCHAR(500) NOT NULL,
    type           VARCHAR(20) NOT NULL,
    signed         BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT documents_type_check CHECK (type IN ('SOURCE', 'RESULT'))
);

CREATE TABLE IF NOT EXISTS payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE RESTRICT,
    amount         NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payments_status_check CHECK (status IN ('PENDING', 'PAID', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS notifications (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    application_id BIGINT REFERENCES applications(id) ON DELETE SET NULL,
    type           VARCHAR(30) NOT NULL,
    message        VARCHAR(2000) NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notifications_type_check CHECK (type IN
        ('APPLICATION_CREATED', 'STATUS_CHANGED', 'DOCUMENTS_READY',
         'APPLICATION_REJECTED', 'APPLICATION_CANCELLED')),
    CONSTRAINT notifications_status_check CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type  VARCHAR(50) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_applications_client_id ON applications(client_id);
CREATE INDEX IF NOT EXISTS idx_applications_service_id ON applications(service_id);
CREATE INDEX IF NOT EXISTS idx_applications_status ON applications(status);
CREATE INDEX IF NOT EXISTS idx_documents_application_id ON documents(application_id);
CREATE INDEX IF NOT EXISTS idx_payments_application_id ON payments(application_id);
CREATE INDEX IF NOT EXISTS idx_notifications_client_id ON notifications(client_id);
CREATE INDEX IF NOT EXISTS idx_notifications_application_id ON notifications(application_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON audit_log(created_at);

COMMENT ON TABLE clients IS 'Клиенты нотариальной конторы';
COMMENT ON TABLE services IS 'Каталог нотариальных услуг и тарифов';
COMMENT ON TABLE applications IS 'Заявки клиентов на нотариальные услуги';
COMMENT ON TABLE documents IS 'Исходные и готовые документы по заявкам';
COMMENT ON TABLE payments IS 'Платежи через учебную платёжную заглушку';
COMMENT ON TABLE notifications IS 'Уведомления клиентов о событиях заявок';
COMMENT ON TABLE audit_log IS 'Журнал событий создания заявок и изменения статусов';

